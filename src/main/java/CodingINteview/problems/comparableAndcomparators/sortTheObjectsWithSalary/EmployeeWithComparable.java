package CodingINteview.problems.comparableAndcomparators.sortTheObjectsWithSalary;

public class EmployeeWithComparable {

    public String name;

    public int salary;

    public EmployeeWithComparable(String name, int salary) {
        this.name = name;
        this.salary = salary;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getSalary() {
        return salary;
    }

    public void setSalary(int salary) {
        this.salary = salary;
    }

    @Override
    public String toString() {
        return "Employee{" +
                "name='" + name + '\'' +
                ", salary=" + salary +
                '}';
    }
}
